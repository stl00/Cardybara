// Cache-first for the app shell, which is listed by file name and versioned by content, so an update replaces the
// whole cache at once. Everything else on this origin is cached when first used; other origins and non-GET
// requests, the gateway included, never touch the worker.
export function serviceWorkerSource(shell, version) {
  return `// Generated by scripts/web-build.mjs. Do not edit.
const CACHE = ${JSON.stringify('cardybara-web-' + version)};
const SHELL = ${JSON.stringify(shell)};
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(SHELL)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', event => {
  event.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('cardybara-web-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', event => {
  const request = event.request, url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin || url.pathname === '/data.json' || url.pathname === '/sw.js') return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const hit = await cache.match(request.mode === 'navigate' ? '/index.html' : request, {ignoreSearch: request.mode !== 'navigate'});
    if (hit) return hit;
    try {
      const response = await fetch(request);
      if (response.ok && response.type === 'basic') cache.put(request, response.clone());
      return response;
    } catch (error) {
      if (request.mode === 'navigate') { const page = await cache.match('/index.html'); if (page) return page; }
      throw error;
    }
  })());
});
`;
}

const walk = dir => readdirSync(dir, {withFileTypes: true}).flatMap(e => e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)]);

export function webAppPlugin({root, env = process.env}) {
  const rootDir = root instanceof URL ? root.pathname : root;
  const gateway = gatewayOrigin(env);
  let outDir;
  return {
    name: 'cardybara-web-app',
    apply: 'build',
    enforce: 'pre',
    configResolved(config) { outDir = config.build.outDir.startsWith('/') ? config.build.outDir : join(config.root, config.build.outDir); },
    transformIndexHtml: {
      order: 'pre',
      handler: () => [
        {tag: 'meta', attrs: {name: 'theme-color', content: THEME.light, media: '(prefers-color-scheme: light)'}, injectTo: 'head'},
        {tag: 'meta', attrs: {name: 'theme-color', content: THEME.dark, media: '(prefers-color-scheme: dark)'}, injectTo: 'head'},
        {tag: 'link', attrs: {rel: 'manifest', href: '/manifest.webmanifest'}, injectTo: 'head'},
        // iOS Home Screen: a 180 px PNG on an opaque background (an SVG or transparent PNG shows as a blank tile).
        {tag: 'link', attrs: {rel: 'apple-touch-icon', sizes: '180x180', href: '/apple-touch-icon.png'}, injectTo: 'head'},
        {tag: 'meta', attrs: {name: 'apple-mobile-web-app-title', content: 'Cardybara'}, injectTo: 'head'},
        {tag: 'script', attrs: {type: 'module', src: '/web/shell.js'}, injectTo: 'head-prepend'},
      ],
    },
    closeBundle() {
      // Static files the wallet links to by path. public/ is not copied wholesale: it can hold a local data.json
      // and review pages that are not part of the app.
      copyFileSync(join(rootDir, 'public/cardybara.svg'), join(outDir, 'cardybara.svg'));
      // Also at the root path, which iOS requests by itself when a page has no link.
      copyFileSync(join(rootDir, 'public/brand/app-icons/apple-touch-icon.png'), join(outDir, 'apple-touch-icon.png'));
      for (const folder of ['assets', 'brand']) {
        const from = join(rootDir, 'public', folder);
        if (existsSync(from)) cpSync(from, join(outDir, folder), {recursive: true, filter: p => !p.split('/').includes('archive') && (statSync(p).isDirectory() || IMAGES.has(extname(p).toLowerCase()))});
      }
      writeFileSync(join(outDir, 'manifest.webmanifest'), JSON.stringify(webManifest(), null, 2) + '\n');
      writeFileSync(join(outDir, '_headers'), webHeaders(gateway));
      const files = walk(outDir).map(p => p.slice(outDir.length + 1)).sort();
      const shell = ['/', ...files.filter(f => f === 'index.html' || f === 'manifest.webmanifest' || f === 'cardybara.svg' || /^assets\/[^/]+\.(js|css)$/.test(f)).map(f => '/' + f)];
      const hash = createHash('sha256');
      for (const f of shell.filter(f => f !== '/')) hash.update(f).update(readFileSync(join(outDir, f)));
      writeFileSync(join(outDir, 'sw.js'), serviceWorkerSource(shell, hash.digest('hex').slice(0, 12)));
    },
  };
}
