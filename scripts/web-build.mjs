// `npm run build:web` (stl00/Cardybara#374): the wallet as a static, installable web app in dist/web.
// Same Vite app from src/ as the extension build; only this plugin and web/shell.js differ. Output is a deployable
// folder, nothing is published from here. The site headers allow only this origin plus, when set, the gateway.
import {copyFileSync, cpSync, existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {extname, join} from 'node:path';

export const WEB_OUT = 'dist/web';
const IMAGES = new Set(['.png', '.jpg', '.jpeg', '.svg', '.webp', '.ico']);
export const THEME = {light: '#1677ff', dark: '#141414'};

// CARDYBARA_GATEWAY_ORIGIN: the gateway's https origin, nothing more. Unset means no other origin is allowed.
export function gatewayOrigin(env = process.env) {
  const raw = (env.CARDYBARA_GATEWAY_ORIGIN || '').trim();
  if (!raw) return null;
  let url;
  try { url = new URL(raw); } catch { throw new Error('CARDYBARA_GATEWAY_ORIGIN is not a URL'); }
  const local = url.hostname === 'localhost' || url.hostname === '127.0.0.1';
  if ((url.protocol !== 'https:' && !(local && url.protocol === 'http:')) || url.origin !== raw.replace(/\/$/, '') || url.username || url.password) {
    throw new Error('CARDYBARA_GATEWAY_ORIGIN must be a bare https origin such as https://gateway.example');
  }
  return url.origin;
}

export function webHeaders(gateway = null) {
  const csp = [
    "default-src 'none'",
    "script-src 'self'",
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob:",
    "font-src 'self' data:",
    `connect-src 'self'${gateway ? ' ' + gateway : ''}`,
    "manifest-src 'self'",
    "worker-src 'self'",
    "base-uri 'none'",
    "form-action 'none'",
    "frame-ancestors 'none'",
  ].join('; ');
  return `/*
  Content-Security-Policy: ${csp}
  Referrer-Policy: no-referrer
  X-Content-Type-Options: nosniff
  Permissions-Policy: interest-cohort=()
/sw.js
  Cache-Control: no-cache
/index.html
  Cache-Control: no-cache
/manifest.webmanifest
  Cache-Control: no-cache
/assets/*
  Cache-Control: public, max-age=31536000, immutable
`;
}

